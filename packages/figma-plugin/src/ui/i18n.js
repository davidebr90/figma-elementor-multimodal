const localeKey = (locale) => String(locale || '').toLowerCase().split('-')[0];

export function createTranslator(locale) {
  const catalogue = catalogues[localeKey(locale)] || catalogues.en;
  return (key) => catalogue[key] || catalogues.en[key] || key;
}
